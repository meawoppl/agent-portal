#!/usr/bin/env bash
# Write deploy/.env for docker compose: asks for the domain and a login
# provider, generates every secret, and prints the exact OAuth callback URL to
# register. Refuses to overwrite an existing .env — its secrets sign every
# cookie and token, and its database password is baked into the db volume.
set -euo pipefail

cd "$(dirname "$0")"

if [[ -e .env ]]; then
  echo "deploy/.env already exists; edit it directly or move it aside first." >&2
  exit 1
fi

# ask PROMPT PATTERN [DEFAULT] — re-prompt until the answer matches PATTERN.
ask() {
  local prompt=$1 pattern=$2 default=${3:-} reply
  while true; do
    read -r -p "$prompt${default:+ [$default]}: " reply
    reply=${reply:-$default}
    [[ $reply =~ $pattern ]] && { echo "$reply"; return; }
    echo "  That doesn't look right; try again." >&2
  done
}

# Like ask, without echoing the typed value.
ask_secret() {
  local prompt=$1 reply=""
  while [[ -z $reply || $reply == *"'"* ]]; do
    read -r -s -p "$prompt: " reply
    echo >&2
    [[ $reply == *"'"* ]] && echo "  Values containing ' are not supported." >&2
  done
  echo "$reply"
}

secret() {
  local value
  value=$(openssl rand -base64 "$1" | tr -d '\n/+=')
  [[ ${#value} -ge $2 ]] || { echo "openssl failed to generate a secret" >&2; exit 1; }
  echo "${value:0:$2}"
}

# Generate first: a failure here must not leave a half-written .env.
postgres_password=$(secret 48 40)
session_secret=$(secret 96 64)

# The image for a main-branch commit is tagged major.minor.<commit count>,
# the same version the portal reports, so a checkout knows its own tag.
default_version=""
if git rev-parse --git-dir > /dev/null 2>&1; then
  minor=$(sed -n 's/^version = "\([0-9]*\.[0-9]*\)\..*/\1/p' ../Cargo.toml | head -1)
  default_version="$minor.$(git rev-list --count HEAD)"
fi

hostname_re='^([A-Za-z0-9]([A-Za-z0-9-]{0,61}[A-Za-z0-9])?\.)+[A-Za-z]{2,63}$'
domain=$(ask "Public domain for the portal (DNS must point here), e.g. portal.example.com" "$hostname_re")
acme_email=$(ask "Email for Let's Encrypt certificate notices" "^[^@[:space:]']+@[^@[:space:]']+$")
version=$(ask "Portal version to run (image tag)" '^[0-9]+\.[0-9]+\.[0-9]+$' "$default_version")

echo
echo "Login provider. Create an OAuth app with this callback URL:"
echo "  Google: https://$domain/api/auth/google/callback"
echo "  GitHub: https://$domain/api/auth/github/callback"
provider=$(ask "Provider (google/github)" '^(google|github)$' "github")
prefix=$(tr '[:lower:]' '[:upper:]' <<< "$provider")
client_id=$(ask "$provider OAuth client id" "^[^'[:space:]]+$")
client_secret=$(ask_secret "$provider OAuth client secret (input hidden)")

echo
echo "Who may sign in? Answer '-' to allow any $provider account."
allowed_emails=$(ask "Allowed emails, comma-separated" "^[^'[:space:]]+$" "-")
allowed_domain=$(ask "Allowed email domain" "^[^'[:space:]]+$" "-")

# Single-quoted dotenv values are literal to Compose: a '$' in a credential is
# never interpolated. ask/ask_secret reject values containing a quote.
line() { printf "%s='%s'\n" "$1" "$2"; }

umask 077
tmp=$(mktemp .env.XXXXXX)
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by deploy/setup.sh. Keep this file private and backed up."
  line PORTAL_DOMAIN "$domain"
  line ACME_EMAIL "$acme_email"
  line PORTAL_VERSION "$version"
  line POSTGRES_PASSWORD "$postgres_password"
  line SESSION_SECRET "$session_secret"
  line "${prefix}_CLIENT_ID" "$client_id"
  line "${prefix}_CLIENT_SECRET" "$client_secret"
  line "${prefix}_REDIRECT_URI" "https://$domain/api/auth/$provider/callback"
  if [[ $allowed_emails != "-" ]]; then line ALLOWED_EMAILS "$allowed_emails"; fi
  if [[ $allowed_domain != "-" ]]; then line ALLOWED_EMAIL_DOMAIN "$allowed_domain"; fi
} > "$tmp"
mv "$tmp" .env
trap - EXIT

echo
echo "Wrote deploy/.env. Start the portal with:"
echo "  cd deploy && docker compose up -d"
echo "then open https://$domain"
